"""Compile a project to a Ren'Py `game/` directory (DESIGN.md §11).

One-way: scene YAML in, `.rpy` out. The compiler tracks what is on screen so
every `show` names the full image (`show mira idle smile`), which keeps the
build independent of Ren'Py's attribute-merging rules. Anything whose art or
audio is missing compiles to a Placeholder so the project is playable at every
stage.
"""
from __future__ import annotations

import shutil
from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional

from .project import SPECIAL_SPEAKERS, Project
from .schema import (CG, Affection, CGEnd, Choice, Enter, Exit, If, Jump, Narr, Nsfw, Pause, Say,
                     Scene, SetFlags, Stage, Step, compile_condition)

IND = "    "


def rpy_str(s: str) -> str:
    s = s.replace("\\", "\\\\").replace('"', '\\"').replace("[", "[[").replace("{", "{{")
    return '"' + s.replace("\n", "\\n") + '"'


def ident(s: str) -> str:
    return "".join(ch if ch.isalnum() or ch == "_" else "_" for ch in s)


@dataclass
class Sprite:
    pose: str
    expr: str
    at: str


@dataclass
class State:
    """What is on screen, tracked through the scene so shows are complete."""
    location: str
    time: str
    present: list[str]
    outfits: dict[str, str]
    sprites: dict[str, Sprite] = field(default_factory=dict)
    cg: Optional[str] = None
    line_no: int = 0

    def copy(self) -> "State":
        return State(self.location, self.time, list(self.present), dict(self.outfits),
                     {k: Sprite(v.pose, v.expr, v.at) for k, v in self.sprites.items()}, self.cg, self.line_no)


class Compiler:
    def __init__(self, project: Project):
        self.p = project
        self.images: set[tuple[str, ...]] = set()      # image names used, for declarations
        self.bgs: set[tuple[str, str]] = set()

    # ---- entry ---------------------------------------------------------------

    def build(self, out: Path, scene_ids: Optional[list[str]] = None, template: Optional[Path] = None) -> list[Path]:
        game = out / "game"
        if game.exists():
            shutil.rmtree(game)
        (game / "scenes").mkdir(parents=True)
        written = []
        scenes = self.p.load_scenes()
        for sid in (scene_ids or sorted(scenes)):
            text = self.compile_scene(scenes[sid])
            path = game / "scenes" / f"{ident(sid)}.rpy"
            path.write_text(text, encoding="utf-8")
            written.append(path)
        (game / "script.rpy").write_text(self.script_rpy(), encoding="utf-8")
        (game / "characters.rpy").write_text(self.characters_rpy(), encoding="utf-8")
        (game / "options.rpy").write_text(self.options_rpy(), encoding="utf-8")
        for sub in ("images", "audio"):
            src = self.p.root / sub
            if src.exists():
                shutil.copytree(src, game / sub, dirs_exist_ok=True,
                                ignore=shutil.ignore_patterns(".gitkeep", "takes", "candidates"))
        if template:
            # gui.rpy, screens.rpy and gui/ from a launcher-made project give the real menus
            for name in ("gui.rpy", "screens.rpy", "gui"):
                s = template / "game" / name
                if s.is_dir():
                    shutil.copytree(s, game / name, dirs_exist_ok=True)
                elif s.exists():
                    shutil.copy2(s, game / name)
        return written

    # ---- top-level files ------------------------------------------------------

    def script_rpy(self) -> str:
        p = self.p
        lines = ["# generated by vn build -- do not edit", ""]
        lines.append("default affection = {" + ", ".join(f'"{c}": 0' for c in p.characters) + "}")
        lines.append("default flags = {" + ", ".join(f'"{k}": {v!r}' for k, v in p.outline.flags.items()) + "}")
        lines += ["", "label start:", f"{IND}jump scene_{ident(p.outline.start)}", ""]
        return "\n".join(lines)

    def characters_rpy(self) -> str:
        p = self.p
        lines = ["# generated by vn build -- do not edit", "",
                 'define narrator = Character(None)',
                 'define player = Character("[player_name]")',
                 'default player_name = ' + rpy_str(self._player_name()), ""]
        for cid, c in p.characters.items():
            colour = f', color="{c.appearance.color}"' if c.appearance.color else ""
            lines.append(f'define {ident(cid)} = Character({rpy_str(c.appearance.display_name)}, voice_tag="{ident(cid)}"{colour})')
        lines.append("")
        for loc, t in sorted(self.bgs):
            f = f"images/bg/{loc}_{t}.png"
            if (p.root / f).exists():
                lines.append(f'image bg {ident(loc)}_{ident(t)} = "{f}"')
            else:
                lines.append(f'image bg {ident(loc)}_{ident(t)} = Placeholder("bg", text={rpy_str(f"{loc} / {t}")})')
        lines.append("")
        for name in sorted(self.images):
            kind = name[0]
            if kind == "cg":
                f = f"images/cg/{name[1]}.png"
                if (p.root / f).exists():
                    lines.append(f'image cg {ident(name[1])} = "{f}"')
                else:
                    lines.append(f'image cg {ident(name[1])} = Placeholder("bg", text={rpy_str("CG " + name[1])})')
            else:
                cid, outfit, pose, expr = name
                f = f"characters/{cid}/art/sprites/{outfit}_{pose}_{expr}.png"
                tag = " ".join(ident(x) for x in (cid, outfit, pose, expr))
                if (p.root / f).exists():
                    lines.append(f'image {tag} = "{self._sprite_build_path(cid, outfit, pose, expr)}"')
                else:
                    kind_ph = "girl" if "1girl" in p.characters[cid].appearance.base_tags else "boy"
                    lines.append(f'image {tag} = Placeholder("{kind_ph}", text={rpy_str(f"{cid} {outfit} {pose} {expr}")})')
        return "\n".join(lines) + "\n"

    def _sprite_build_path(self, cid: str, outfit: str, pose: str, expr: str) -> str:
        # sprites are copied under images/sprites/<cid>/ at build time
        return f"images/sprites/{cid}/{outfit}_{pose}_{expr}.png"

    def options_rpy(self) -> str:
        title = self._title()
        return "\n".join(["# generated by vn build -- do not edit", "",
                          f"define config.name = {rpy_str(title)}",
                          'define config.version = "0.1"',
                          f"define build.name = {rpy_str(ident(title) or 'vn')}",
                          "define config.has_sound = True",
                          "define config.has_music = True",
                          "define config.has_voice = True", ""])

    def _title(self) -> str:
        for line in self.p.premise.splitlines():
            if line.startswith("# "):
                return line[2:].strip()
        return self.p.root.name

    def _player_name(self) -> str:
        import re
        m = re.search(r"^## The player\s*\n+(?:\s*-?\s*)?(?:Name:?\s*)?([A-Z][\w'-]*)", self.p.premise, re.M)
        return m.group(1) if m else "You"

    # ---- scenes -----------------------------------------------------------------

    def compile_scene(self, sc: Scene) -> str:
        p = self.p
        outfits = {cid: p.characters[cid].appearance.default_outfit for cid in p.characters if cid in p.characters}
        outfits.update(sc.outfits)
        st = State(sc.location, sc.time, list(sc.present), outfits)
        out = [f"# {sc.id}: {sc.title}", f"label scene_{ident(sc.id)}:"]
        body: list[str] = []
        self._emit_bg(body, st, "fade")
        for cid in sc.present:
            self._show(body, st, cid, "idle", "neutral", self._default_pos(sc.present, cid))
        self._emit_steps(body, st, sc.steps, sc)
        if sc.next:
            body.append(f"jump scene_{ident(sc.next)}")
        else:
            body.append("return")
        out += [IND + l if l else "" for l in body]
        return "\n".join(out) + "\n"

    def _default_pos(self, present: list[str], cid: str) -> str:
        if len(present) == 1:
            return "center"
        return ["left", "right", "center"][present.index(cid) % 3]

    def _emit_steps(self, out: list[str], st: State, steps: list[Step], sc: Scene) -> None:
        for s in steps:
            self._emit_step(out, st, s, sc)

    def _emit_step(self, out: list[str], st: State, s: Step, sc: Scene) -> None:
        if isinstance(s, Narr):
            out.append(rpy_str(s.text))
        elif isinstance(s, Say):
            if s.speaker in SPECIAL_SPEAKERS:
                out.append(f"{s.speaker} {rpy_str(s.text)}")
                return
            cur = st.sprites.get(s.speaker)
            if st.cg is None:
                if cur is None:
                    self._show(out, st, s.speaker, s.pose or "idle", s.expr or "neutral", self._default_pos(st.present, s.speaker))
                elif (s.pose and s.pose != cur.pose) or (s.expr and s.expr != cur.expr):
                    self._show(out, st, s.speaker, s.pose or cur.pose, s.expr or cur.expr, cur.at)
            st.line_no += 1
            voice = f"audio/voice/{sc.id}/{st.line_no:03d}.ogg"
            if (self.p.root / voice).exists():
                out.append(f'voice "{voice}"')
            out.append(f"{ident(s.speaker)} {rpy_str(s.text)}")
        elif isinstance(s, Stage):
            if s.outfits:
                st.outfits.update(s.outfits)
            changed = (s.location and s.location != st.location) or (s.time and s.time != st.time)
            if s.location:
                st.location = s.location
            if s.time:
                st.time = s.time
            if s.present is not None:
                st.present = list(s.present)
            if changed or s.outfits:
                self._emit_bg(out, st, s.transition or "dissolve")
                st.sprites = {}
                for cid in st.present:
                    self._show(out, st, cid, "idle", "neutral", self._default_pos(st.present, cid))
            elif s.present is not None:
                for cid in list(st.sprites):
                    if cid not in st.present:
                        out.append(f"hide {ident(cid)}")
                        del st.sprites[cid]
        elif isinstance(s, Enter):
            if s.char not in st.present:
                st.present.append(s.char)
            self._show(out, st, s.char, s.pose or "idle", s.expr or "neutral",
                       s.at or self._default_pos(st.present, s.char), s.transition or "dissolve")
        elif isinstance(s, Exit):
            if s.char in st.present:
                st.present.remove(s.char)
            if s.char in st.sprites:
                del st.sprites[s.char]
                out.append(f"hide {ident(s.char)} with {s.transition or 'dissolve'}")
        elif isinstance(s, SetFlags):
            for k, v in s.values.items():
                out.append(f'$ flags["{k}"] = {v!r}')
        elif isinstance(s, Affection):
            for cid, d in s.deltas.items():
                out.append(f'$ affection["{cid}"] += {d}')
        elif isinstance(s, CG):
            self.images.add(("cg", s.id))
            st.cg = s.id
            st.sprites = {}
            out.append(f"scene cg {ident(s.id)} with {s.transition or 'dissolve'}")
        elif isinstance(s, CGEnd):
            st.cg = None
            self._emit_bg(out, st, s.transition or "dissolve")
            for cid in st.present:
                self._show(out, st, cid, "idle", "neutral", self._default_pos(st.present, cid))
        elif isinstance(s, Choice):
            out.append("menu:")
            running, touched = st.line_no, False
            if s.prompt:
                out.append(IND + rpy_str(s.prompt))
            for o in s.options:
                cond = f" if {compile_condition(o.requires)}" if o.requires else ""
                out.append(f"{IND}{rpy_str(o.text)}{cond}:")
                sub: list[str] = []
                for cid, d in (o.effects.get("affection") or {}).items():
                    sub.append(f'$ affection["{cid}"] += {d}')
                for k, v in (o.effects.get("set") or {}).items():
                    sub.append(f'$ flags["{k}"] = {v!r}')
                branch_state = st.copy()
                branch_state.line_no = running          # voice files number depth-first, like Project.lines()
                self._emit_steps(sub, branch_state, o.steps, sc)
                running = branch_state.line_no
                touched |= branch_state.sprites != st.sprites
                if o.goto:
                    sub.append(f"jump scene_{ident(o.goto)}")
                elif not sub:
                    sub.append("pass")
                out += [IND * 2 + l for l in sub]
            st.line_no = running
            if touched:
                self._resync(out, st)
        elif isinstance(s, If):
            out.append(f"if {compile_condition(s.cond)}:")
            then_state = st.copy()
            sub: list[str] = []
            self._emit_steps(sub, then_state, s.then, sc)
            out += [IND + l for l in sub] or [IND + "pass"]
            else_state = st.copy()
            else_state.line_no = then_state.line_no
            if s.else_:
                out.append("else:")
                sub = []
                self._emit_steps(sub, else_state, s.else_, sc)
                out += [IND + l for l in sub]
            st.line_no = else_state.line_no
            if then_state.sprites != st.sprites or else_state.sprites != st.sprites:
                self._resync(out, st)
        elif isinstance(s, Nsfw):
            fill = self.p.nsfw_fill(s.ref)
            if fill is None:
                out.append(rpy_str(f"[explicit section {s.ref} is not filled in yet]"))
            else:
                self._emit_steps(out, st, fill, sc)
        elif isinstance(s, Jump):
            out.append(f"jump scene_{ident(s.target)}")
        elif isinstance(s, Pause):
            out.append(f"pause {s.seconds}")
        else:
            raise TypeError(f"unhandled step {s!r}")

    def _resync(self, out: list[str], st: State) -> None:
        """Branches may have changed sprites; after a menu/if force the known state back."""
        if st.cg is not None:
            return
        for cid, sp in list(st.sprites.items()):
            self._show(out, st, cid, sp.pose, sp.expr, sp.at)

    def _emit_bg(self, out: list[str], st: State, transition: str) -> None:
        self.bgs.add((st.location, st.time))
        out.append(f"scene bg {ident(st.location)}_{ident(st.time)}" + (f" with {transition}" if transition != "none" else ""))

    def _show(self, out: list[str], st: State, cid: str, pose: str, expr: str, at: str, transition: Optional[str] = None) -> None:
        if cid not in self.p.characters:
            return
        outfit = st.outfits.get(cid, self.p.characters[cid].appearance.default_outfit)
        self.images.add((cid, outfit, pose, expr))
        st.sprites[cid] = Sprite(pose, expr, at)
        tag = " ".join(ident(x) for x in (cid, outfit, pose, expr))
        out.append(f"show {tag} at {at}" + (f" with {transition}" if transition else ""))


def build(project: Project, out: Path, scene_ids: Optional[list[str]] = None, template: Optional[Path] = None) -> list[Path]:
    c = Compiler(project)
    written = c.build(out, scene_ids, template)
    # sprites live under characters/<id>/art/sprites in the project; copy to images/sprites/<id>
    for cid, ch in project.characters.items():
        src = ch.dir / "art" / "sprites"
        if src.exists():
            shutil.copytree(src, out / "game" / "images" / "sprites" / cid, dirs_exist_ok=True)
    return written
